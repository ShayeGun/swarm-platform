#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  CREATE USER ${JIRA_DB_USER:-jira} WITH PASSWORD '${JIRA_DB_PASSWORD:-change-me}';
  CREATE DATABASE ${JIRA_DB:-jira} OWNER ${JIRA_DB_USER:-jira};

  CREATE USER ${KEYCLOAK_DB_USER:-keycloak} WITH PASSWORD '${KEYCLOAK_DB_PASSWORD:-change-me}';
  CREATE DATABASE ${KEYCLOAK_DB:-keycloak} OWNER ${KEYCLOAK_DB_USER:-keycloak};

  CREATE USER ${MATTERMOST_DB_USER:-mattermost} WITH PASSWORD '${MATTERMOST_DB_PASSWORD:-change-me}';
  CREATE DATABASE ${MATTERMOST_DB:-mattermost} OWNER ${MATTERMOST_DB_USER:-mattermost};
EOSQL
